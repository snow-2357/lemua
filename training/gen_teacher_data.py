import os
import shutil
import numpy as np
import soundfile as sf
from kokoro import KPipeline

# 1. Configuration
TEXT_FILE = "sentences.txt"
OUTPUT_DIR = "dataset_cache"
os.makedirs(OUTPUT_DIR, exist_ok=True)

if os.path.exists(OUTPUT_DIR):
    shutil.rmtree(OUTPUT_DIR)
    print(f"Cleaned existing '{OUTPUT_DIR}' directory.")

if not os.path.exists(TEXT_FILE):
    raise FileNotFoundError(
        f"Could not find {TEXT_FILE}. Create it with one sentence per line."
    )

print("Initializing Kokoro pipeline...")
# Initialize pipeline for American English ('a') or British English ('b')
pipeline = KPipeline(lang_code="a")

with open(TEXT_FILE, "r", encoding="utf-8") as f:
    sentences = [line.strip() for line in f if line.strip()]

print(f"Loaded {len(sentences)} sentences. Starting extraction...")

# 2. Processing Loop
for idx, text in enumerate(sentences):
    file_id = f"sentence_{idx:04d}"
    print(f"[{idx+1}/{len(sentences)}] Processing: {text}")

    # FIX: Create the sentence-specific subfolder FIRST before writing files into it
    sentence_dir = os.path.join(OUTPUT_DIR, file_id)
    os.makedirs(sentence_dir, exist_ok=True)

    # Run text through the pipeline generator
    try:
        generator = pipeline(text, voice="af_heart")
        for i, (gs, ps, audio) in enumerate(generator):
            # gs = grapheme chunk (original text)
            # ps = phonemes string generated by G2P
            # audio = numpy array of the 24kHz target waveform

            if ps is None or audio is None or isinstance(audio, str):
                continue

            print(f"  -> Phonemes: {ps}")

            # 3. Simulate/Extract intermediate structural representations
            if isinstance(ps, str):
                token_ids = np.array([ord(c) for c in ps], dtype=np.int64)
            else:
                token_ids = np.array(ps, dtype=np.int64)
            dummy_durations = np.ones(len(token_ids), dtype=np.float32) * 3.0
            dummy_pitch = np.linspace(
                110.0, 130.0, num=len(audio) // 256, dtype=np.float32
            )
            dummy_loudness = np.ones(len(audio) // 256, dtype=np.float32) * 0.5

            # 4. Save everything side-by-side to disk safely
            # Instead of saving text as a binary .npy, use a plain .txt file if you want it readable:
            with open(
                os.path.join(sentence_dir, "text.txt"), "w", encoding="utf-8"
            ) as tf:
                tf.write(text)
            audio_np = audio.detach().cpu().numpy()
            sf.write(os.path.join(sentence_dir, "audio.wav"), audio_np, 24000)
            np.save(os.path.join(sentence_dir, "tokens.npy"), token_ids)
            np.save(os.path.join(sentence_dir, "durations.npy"), dummy_durations)
            np.save(os.path.join(sentence_dir, "pitch.npy"), dummy_pitch)
            np.save(os.path.join(sentence_dir, "loudness.npy"), dummy_loudness)

            print(f"  -> Saved targets and audio for {file_id}")
            break
    except Exception as e:
        print(f"Error occurred while processing sentence {idx+1}: {e}")
        continue


print("\nExtraction complete! Check your 'dataset_cache' folder.")
